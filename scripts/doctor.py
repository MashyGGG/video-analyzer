"""Cross-platform environment check; GPU is optional unless --require-gpu is supplied."""

import argparse
import json
import platform
import subprocess
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def command(args: list[str], timeout: int = 15) -> tuple[int, str]:
    try:
        result = subprocess.run(
            args,
            cwd=ROOT,
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=timeout,
            check=False,
        )
        return result.returncode, result.stdout.strip()
    except (OSError, subprocess.TimeoutExpired):
        return 127, ""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--require-gpu", action="store_true")
    parser.add_argument("--services", action="store_true")
    parser.add_argument("--api-port", type=int, default=8000)
    parser.add_argument("--web-port", type=int, default=3100)
    parser.add_argument("--compose-project", default=None)
    args = parser.parse_args()
    compose = ["docker", "compose"] + (["-p", args.compose_project] if args.compose_project else [])
    checks = []

    def add(name: str, status: str, detail: str) -> None:
        checks.append(dict(name=name, status=status, detail=detail))

    for name, argv in [
        ("docker", ["docker", "version", "--format", "{{.Server.Version}}"]),
        ("compose", ["docker", "compose", "version", "--short"]),
    ]:
        code, output = command(argv)
        add(
            name,
            "PASS" if code == 0 else "FAIL",
            output if code == 0 else "Tool/daemon unavailable",
        )
    code, output = command([*compose, "config", "--format", "json"])
    try:
        config = json.loads(output) if code == 0 else {}
        valid = set(config["services"]) == {
            "postgres", "redis", "migrate", "api", "worker", "frontend",
            "worker-download", "worker-media", "egress",
        } and config["networks"]["backend"]["internal"] is True
    except (KeyError, ValueError):
        valid = False
    add(
        "compose_config",
        "PASS" if valid else "FAIL",
        "9 A01/A02 services" if valid else "Invalid configuration",
    )
    try:
        import init_local

        # Validation path is idempotent; missing secrets must not be generated by doctor.
        if not all((ROOT / ".secrets" / name).is_file() for name in ("postgres_password", "redis_password")):
            raise ValueError()
        import contextlib
        import io

        with contextlib.redirect_stdout(io.StringIO()):
            init_local.initialize(ROOT)
        add("local_secrets", "PASS", "Present and valid; values hidden")
    except (ValueError, OSError):
        add(
            "local_secrets",
            "FAIL",
            "Run python scripts/init_local.py or restore existing credentials",
        )
    code, output = command(
        [
            "nvidia-smi",
            "--query-gpu=name,memory.total,driver_version",
            "--format=csv,noheader",
        ]
    )
    gpu_ready = code == 0 and bool(output)
    add(
        "nvidia_gpu",
        "PASS" if gpu_ready else "BLOCKED",
        output if gpu_ready else "No NVIDIA GPU/driver evidence; CPU services may run",
    )
    if args.services:
        for name, url in [
            ("api", f"http://127.0.0.1:{args.api_port}/api/v1/health/ready"),
            ("frontend", f"http://127.0.0.1:{args.web_port}/health/live"),
        ]:
            try:
                with urllib.request.urlopen(url, timeout=8) as response:
                    data = json.load(response)
                success = data.get("status") in ("ready", "alive")
            except Exception:
                success = False
            add(
                name,
                "PASS" if success else "FAIL",
                "HTTP ready" if success else "Unavailable",
            )
        code, output = command([*compose, "ps", "--all", "--format", "json"])
        try:
            rows = [json.loads(line) for line in output.splitlines() if line.strip()]
            worker = next(row for row in rows if row["Service"] == "worker")
            healthy = code == 0 and worker.get("Health") == "healthy"
        except (ValueError, KeyError, StopIteration):
            healthy = False
        add(
            "worker",
            "PASS" if healthy else "FAIL",
            "Celery inspect ping healthcheck" if healthy else "Worker not healthy",
        )
    failed = sum(check["status"] == "FAIL" for check in checks)
    print(
        json.dumps(
            dict(
                host={
                    "os": platform.system(),
                    "release": platform.release(),
                    "architecture": platform.machine(),
                    "python": platform.python_version(),
                },
                checks=checks,
                gpu_inference_tested=False,
                base_status="PASS" if failed == 0 else "FAIL",
            ),
            ensure_ascii=False,
            indent=2,
        )
    )
    return 1 if failed else 2 if args.require_gpu and not gpu_ready else 0


if __name__ == "__main__":
    raise SystemExit(main())
